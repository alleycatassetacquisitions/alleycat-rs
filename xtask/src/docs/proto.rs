use crate::project::project_root;
use anyhow::{Context, Result, bail};
use std::{fs, path::Path, process::Command};

const IMAGE: &str = "pseudomuto/protoc-gen-doc:1.5.1";

pub(super) fn generate(check: bool) -> Result<()> {
    let root = project_root()?;
    let source = root.join("proto");
    let output = root.join(format!("target/proto-docs-{}", std::process::id()));
    fs::create_dir_all(&output)?;
    let result = (|| {
        let mut files = Vec::new();
        collect_protos(&source, &source, &mut files)?;
        files.sort();
        if files.is_empty() {
            bail!("no .proto files found");
        }
        let status = Command::new("docker")
            .args([
                "run",
                "--rm",
                "--network",
                "none",
                "--platform",
                "linux/amd64",
            ])
            .arg("--volume")
            .arg(format!("{}:/protos:ro", source.display()))
            .arg("--volume")
            .arg(format!("{}:/out", output.display()))
            .args([IMAGE, "--doc_opt=html,index.html"])
            .args(&files)
            .status()
            .context("could not start Docker; install Docker and start its daemon")?;
        if !status.success() {
            bail!("protobuf documentation generator failed: {status}");
        }
        let html = localize(fs::read_to_string(output.join("index.html"))?)?;
        let destination = root.join("static/device-apis/index.html");
        if check {
            if fs::read_to_string(&destination).ok().as_deref() != Some(html.as_str()) {
                bail!("device API documentation is stale; run cargo xtask docs proto");
            }
            println!("Device API documentation is current.");
        } else {
            fs::create_dir_all(destination.parent().unwrap())?;
            fs::write(&destination, html)?;
            println!("Generated {}", destination.display());
        }
        Ok(())
    })();
    let _ = fs::remove_dir_all(&output);
    result
}

fn collect_protos(root: &Path, directory: &Path, files: &mut Vec<String>) -> Result<()> {
    for entry in fs::read_dir(directory)? {
        let entry = entry?;
        let kind = entry.file_type()?;
        if kind.is_dir() {
            collect_protos(root, &entry.path(), files)?;
        } else if kind.is_file() && entry.path().extension().is_some_and(|ext| ext == "proto") {
            files.push(
                entry
                    .path()
                    .strip_prefix(root)?
                    .to_string_lossy()
                    .into_owned(),
            );
        }
    }
    Ok(())
}

// Use the upstream renderer unchanged for schemas, comments, and cross-links.
// Only adapt its page shell. Fail explicitly if a generator upgrade changes it.
fn localize(mut html: String) -> Result<String> {
    for (from, to) in [
        ("<html>", "<html lang=\"en\">"),
        (
            "<meta charset=\"UTF-8\">",
            "<meta charset=\"UTF-8\">\n    <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">",
        ),
        (
            "<link rel=\"stylesheet\" type=\"text/css\" href=\"https://fonts.googleapis.com/css?family=Ubuntu:400,700,400italic\"/>",
            "",
        ),
        ("\"Ubuntu\", sans-serif", "system-ui, sans-serif"),
        ("href=\"stylesheet.css\"", "href=\"/docs/device-apis.css\""),
        (
            "<title>Protocol Documentation</title>",
            "<title>Device APIs · Alleycat</title>",
        ),
        (
            "<h1 id=\"title\">Protocol Documentation</h1>",
            "<nav aria-label=\"Documentation\"><a href=\"/\">Alleycat</a> / <a href=\"/docs\">HTTP API docs</a> / Device APIs</nav>\n    <h1 id=\"title\">Device APIs</h1>\n    <p>Protobuf messages sent by devices over HTTP. See the <a href=\"/docs\">HTTP API docs</a> for routes, status codes, and upload behavior, or download the <a href=\"/docs/device_api.proto\">protobuf definition</a>.</p>\n    <p>The Label column describes protobuf wire presence. Server-required fields and validation limits are documented in each field’s description.</p>",
        ),
    ] {
        if !html.contains(from) {
            bail!("unexpected protoc-gen-doc page shell: missing {from:?}");
        }
        html = html.replace(from, to);
    }
    Ok(format!(
        "<!-- Generated by cargo xtask docs proto; do not edit. -->\n{html}"
    ))
}
